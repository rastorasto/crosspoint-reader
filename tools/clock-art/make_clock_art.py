#!/usr/bin/env python3
"""Generate src/ClockArt.h: the paper-hat cat (2-bit gray) and Japanese date glyphs.

Run with the Pillow venv:  python3 -I make_clock_art.py <cat.bmp> <NotoSansJP.ttf> <out.h>
All bitmaps are 1-bit, rows packed MSB-first, set bit = draw.
"""
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

# Glyphs for the Japanese date line, e.g. 11月16日（月）.
DATE_CHARS = "0123456789月日火水木金土（）"
DATE_PX = 30

CAT_HEIGHT = 340


def pack(img):
    """1-bit PIL image (set = ink) -> (bytes, w, h)."""
    w, h = img.size
    px = img.load()
    rowBytes = (w + 7) // 8
    out = bytearray(rowBytes * h)
    for y in range(h):
        for x in range(w):
            if px[x, y]:
                out[y * rowBytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(out), w, h


def text_bitmap(font, text):
    l, t, r, b = font.getbbox(text)
    img = Image.new("L", (r - l + 2, b - t + 2), 0)
    ImageDraw.Draw(img).text((1 - l, 1 - t), text, font=font, fill=255)
    return img.point(lambda v: 255 if v >= 128 else 0).convert("1")


def emit(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    return f"static const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def main(catPath, fontPath, outPath):
    src = Image.open(catPath).convert("RGBA")
    src = src.crop(src.getchannel("A").getbbox())
    w = round(src.width * CAT_HEIGHT / src.height)
    pad = 6  # room for the dark-mode glow
    im = src.resize((w, CAT_HEIGHT), Image.LANCZOS)
    canvas = Image.new("RGBA", (w + 2 * pad, CAT_HEIGHT + 2 * pad), (0, 0, 0, 0))
    canvas.paste(im, (pad, pad))
    alpha = canvas.getchannel("A")
    gray = canvas.convert("L")
    light = Image.composite(gray, Image.new("L", canvas.size, 255), alpha)
    glow = alpha.filter(ImageFilter.MaxFilter(7)).filter(ImageFilter.GaussianBlur(1.2))
    darkBase = Image.composite(Image.new("L", canvas.size, 255), Image.new("L", canvas.size, 0), glow)
    dark = Image.composite(gray, darkBase, alpha)

    def levels(img):
        # 4 levels: 0 black, 1 dark gray, 2 light gray, 3 white; 2 bits per pixel.
        cw, ch = img.size
        px = img.load()
        rowBytes = (cw + 3) // 4
        out = bytearray(rowBytes * ch)
        for y in range(ch):
            for x in range(cw):
                v = px[x, y]
                lv = 0 if v < 48 else 1 if v < 128 else 2 if v < 208 else 3
                out[y * rowBytes + x // 4] |= lv << (6 - 2 * (x % 4))
        return bytes(out)

    parts = [
        "#pragma once\n// Generated by make_clock_art.py. Do not edit.\n"
        "// Cat: user's own artwork. Japanese glyphs rendered from Noto Sans JP (SIL OFL 1.1).\n"
        "#include <Arduino.h>\n#include <cstdint>\n\nnamespace clockart {\n\n"
        "// Cat as 2-bit levels (0 black .. 3 white), rows MSB-first, 4 pixels per byte.\n"
    ]
    parts.append(emit("CAT_LIGHT", levels(light)))
    parts.append(emit("CAT_DARK", levels(dark)))
    parts.append(f"constexpr int CAT_W = {canvas.width};\nconstexpr int CAT_H = {canvas.height};\n\n")

    # Date glyphs share one line box so they align on the baseline.
    dateFont = ImageFont.truetype(fontPath, DATE_PX)
    dateFont.set_variation_by_axes([700])
    ascent, descent = dateFont.getmetrics()
    glyphEntries = []
    for i, ch in enumerate(DATE_CHARS):
        adv = int(round(dateFont.getlength(ch)))
        img = Image.new("L", (adv, ascent + descent), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=dateFont, fill=255)
        data, w, h = pack(img.point(lambda v: 255 if v >= 128 else 0).convert("1"))
        parts.append(emit(f"DATE_GLYPH{i}", data))
        glyphEntries.append(f"  {{DATE_GLYPH{i}, {w}, {h}}},  // {ch}")
    parts.append(
        "struct Glyph {\n  const uint8_t* bits;\n  uint16_t w, h;\n};\n"
        f"// Index: 0-9 digits, 10 月, 11 日, 12-16 火水木金土, 17 （, 18 ）\n"
        "static const Glyph DATE_GLYPHS[] = {\n" + "\n".join(glyphEntries) + "\n};\n\n"
    )

    parts.append("}  // namespace clockart\n")
    with open(outPath, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print(f"cat {w}x{CAT_HEIGHT} -> {outPath}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
